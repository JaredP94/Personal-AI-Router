import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

interface CssAsset {
    name: string
    url: string
    sha256: string
    outputPath: string
}

const version = '1.0.0'
const outputDir = join(process.cwd(), 'src/ui/lib/kaizen-ui-foundations')
const assets: CssAsset[] = [
    {
        name: 'base-external.css',
        url: `https://webassets.nvidia.com/kaizen-ui-foundations/${version}/base-external.css`,
        sha256: 'd8e74d35082a0f5024bfadd7435e4e8b8dfcfaa09c7bcbbb767fc916c75ac5c7',
        outputPath: join(outputDir, 'base-external.css')
    },
    {
        name: 'components.css',
        url: `https://webassets.nvidia.com/kaizen-ui-foundations/${version}/components.css`,
        sha256: '687cee259883e8952bfc7886cc7200839b10e9a9744a032e397d8f4e9d3ef76b',
        outputPath: join(outputDir, 'components.css')
    }
]

function removeRemoteFontFaces(css: string): string {
    return css.replace(/@font-face\{[^{}]*https?:\/\/[^{}]*\}/g, '')
}

function remoteLoadPattern(): RegExp {
    return /(?:@import\s+(?:url\()?["']?https?:\/\/|url\(["']?https?:\/\/)/g
}

function remoteLoadIndex(css: string): number {
    const match = remoteLoadPattern().exec(css)
    return match?.index ?? -1
}

function remoteUrlSnippet(css: string): string {
    const index = remoteLoadIndex(css)
    if (index === -1) return ''
    const start = Math.max(0, index - 80)
    const end = Math.min(css.length, index + 180)
    return css.slice(start, end)
}

function ensureOfflineCss(css: string, assetName: string): string {
    const offlineCss = removeRemoteFontFaces(css)
    if (remoteLoadIndex(offlineCss) !== -1) {
        throw new Error(
            `${assetName} still contains a remote network load after vendoring: ${remoteUrlSnippet(offlineCss)}`
        )
    }
    return [
        `/* Vendored from Kaizen UI Foundations ${version}.`,
        ' * Generated by scripts/vendor-kaizen-ui-foundations-css.ts.',
        ' * Remote @font-face rules are stripped so the Electron app works offline.',
        ' */',
        offlineCss
    ].join('\n')
}

interface PreparedAsset {
    asset: CssAsset
    offlineCss: string
}

async function prepareAsset(asset: CssAsset): Promise<PreparedAsset> {
    const response = await fetch(asset.url)
    if (!response.ok) {
        throw new Error(`Failed to fetch ${asset.url}: HTTP ${response.status}`)
    }
    const buffer = Buffer.from(await response.arrayBuffer())
    const actualSha256 = createHash('sha256').update(buffer).digest('hex')
    if (actualSha256 !== asset.sha256.toLowerCase()) {
        throw new Error(
            `SHA-256 digest mismatch for ${asset.url}: expected ${asset.sha256}, got ${actualSha256}`
        )
    }
    const css = buffer.toString('utf8')
    const offlineCss = ensureOfflineCss(css, asset.name)
    return { asset, offlineCss }
}

async function main(): Promise<void> {
    const preparedAssets: PreparedAsset[] = []
    for (const asset of assets) {
        preparedAssets.push(await prepareAsset(asset))
    }

    await mkdir(outputDir, { recursive: true })
    for (const { asset, offlineCss } of preparedAssets) {
        await writeFile(asset.outputPath, offlineCss, 'utf8')
        console.log(`Vendored ${asset.name} (${offlineCss.length} bytes)`)
    }
}

main().catch(err => {
    const message = err instanceof Error ? err.message : String(err)
    console.error(message)
    process.exitCode = 1
})
